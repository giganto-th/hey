import AppKit
import Observation
import HeyDomain

/// Watches the general pasteboard for copied text. Memory only; never stores what password managers mark as secret.
@MainActor
@Observable
final class ClipboardService {
    private(set) var history = ClipboardHistory()
    var paused = false

    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private static let secretTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    func start() {
        guard timer == nil else { return }
        let t = Timer(timeInterval: 0.7, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        t.tolerance = 0.2
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != changeCount else { return }
        changeCount = pb.changeCount
        guard !paused else { return }
        let types = Set(pb.types ?? [])
        guard types.isDisjoint(with: Self.secretTypes), let text = pb.string(forType: .string) else { return }
        history.add(text)
    }

    /// Put an old entry back on the clipboard without recording it again as new.
    func copy(_ entry: ClipEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(entry.text, forType: .string)
        changeCount = pb.changeCount
        history.add(entry.text)
    }

    func togglePin(_ id: UUID) { history.togglePin(id) }
    func remove(_ id: UUID) { history.remove(id) }
    func clear() { history.clear() }
}
